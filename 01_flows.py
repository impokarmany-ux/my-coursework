# ШАГ 1. Список всех соединений в записи: кто с кем говорил и сколько байт.
# Цель: отделить сервер игры от рекламы/аналитики/CDN.
from common import load_flows
fl = load_flows()
print('%-5s %-24s %-22s %9s %9s  время(с)' % ('прот', 'сервер', 'клиент', 'кл->срв', 'срв->кл'))
for k, v in sorted(fl.items(), key=lambda x: x[1]['t0']):
    if sum(v['bytes']) < 500:   # пустые/служебные соединения не печатаем
        continue
    print('%-5s %-24s %-22s %9d %9d  %.1f-%.1f' % (k[0], '%s:%d' % k[1], '%s:%d' % k[2], v['bytes'][0], v['bytes'][1],
          v['t0'] % 1000, v['t1'] % 1000))
